"""ابزارهای پردازش متن فارسی (نرمال‌سازی و توکن‌سازی سبک، بدون وابستگی سنگین)."""
import re

# تبدیل حروف عربی به فارسی
_AR_TO_FA = {
    "ي": "ی", "ك": "ک", "ۀ": "ه", "ة": "ه", "أ": "ا",
    "إ": "ا", "آ": "ا", "ؤ": "و", "ئ": "ی", "ٱ": "ا",
}
# حذف اعراب و علائم کوتاه
_DIACRITICS = re.compile(r"[ً-ْٰـ]")
# تبدیل ارقام فارسی/عربی به انگلیسی برای یکدستی
_DIGITS = str.maketrans("۰۱۲۳۴۵۶۷۸۹٠١٢٣٤٥٦٧٨٩", "01234567890123456789")

# کلمات پرتکرار فارسی که بار معنایی ندارند و در جست‌وجو نویز ایجاد می‌کنند
_STOPWORDS = {
    "و", "در", "به", "از", "که", "را", "با", "این", "آن", "است", "هست",
    "برای", "یک", "یه", "تا", "می", "کنم", "کنید", "کند", "کنه", "کردن",
    "چه", "چی", "چیست", "چطور", "چگونه", "آیا", "اگر", "یا", "هم", "نیز",
    "بر", "بی", "شما", "من", "ما", "او", "خود", "دارم", "دارد", "دارید",
    "لازم", "باید", "پیشنهاد", "دستگاه", "دستگاهی", "محصول", "خوب", "بهتر",
    "دهید", "بده", "کمک", "نیاز", "مورد", "درباره", "سلام", "خوبه",
}


def is_stopword(tok: str) -> bool:
    return tok in _STOPWORDS


def normalize(text: str) -> str:
    """نرمال‌سازی متن فارسی برای جست‌وجو."""
    if not text:
        return ""
    for a, b in _AR_TO_FA.items():
        text = text.replace(a, b)
    text = _DIACRITICS.sub("", text)
    text = text.translate(_DIGITS)
    text = text.replace("‌", " ")  # نیم‌فاصله -> فاصله
    text = re.sub(r"[^\w\s]", " ", text)
    text = re.sub(r"\s+", " ", text)
    return text.strip().lower()


def tokenize(text: str) -> list:
    """توکن‌سازی بر مبنای فاصله پس از نرمال‌سازی و حذف کلمات پرتکرار."""
    return [t for t in normalize(text).split() if t not in _STOPWORDS and len(t) > 1]
